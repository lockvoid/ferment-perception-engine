"""EdgeTAM V1 deterministic-stage goldens for the Rust oracle tests.

The origin is NOT this script and NOT the Rust code: it is the PyTorch/
torchvision fixture set the iOS package already carries under
`Packages/FermentEngine/Tests/Fixtures/EdgeTAM/v1/`, generated by
`generate_swift_fixtures.py` from EdgeTAM upstream `7711e012a` against
torch 2.7.0 / torchvision 0.22.0 and pinned by sha256 in its own
`manifest.json`.

This script verifies every one of those digests and then copies the tensors
into `scripts/exports/rust_goldens/edgetam_v1/`, so
`crates/engine-processors/tests/ort_segmentation.rs` grades the Rust stages
against the Python origin's bytes without an iOS checkout on the machine.

    uv run --project scripts/exports/edgetam \
        python scripts/exports/edgetam/gen_rust_goldens.py \
        --ios ../ferment-cuts-ios

A digest that does not match is a hard failure: a golden whose provenance
cannot be proved is worse than no golden.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "rust_goldens" / "edgetam_v1"
FIXTURES = Path("Packages/FermentEngine/Tests/Fixtures/EdgeTAM/v1")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(4 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--ios",
        default="../ferment-cuts-ios",
        help="the iOS checkout carrying the origin fixtures",
    )
    args = parser.parse_args()

    source = (Path(args.ios) / FIXTURES).resolve()
    manifest_path = source / "manifest.json"
    if not manifest_path.exists():
        raise SystemExit(f"no EdgeTAM fixture manifest at {manifest_path}")
    manifest = json.loads(manifest_path.read_text())

    OUT.mkdir(parents=True, exist_ok=True)
    copied = {}
    for name, entry in sorted(manifest["tensors"].items()):
        path = source / entry["path"]
        digest = sha256_file(path)
        if digest != entry["sha256"]:
            raise SystemExit(
                f"{entry['path']}: sha256 {digest} does not match the manifest's "
                f"{entry['sha256']} — the origin bytes changed"
            )
        if path.stat().st_size != entry["byte_count"]:
            raise SystemExit(f"{entry['path']}: byte count does not match the manifest")
        shutil.copyfile(path, OUT / entry["path"])
        copied[name] = {
            "path": entry["path"],
            "dtype": entry["dtype"],
            "shape": entry["shape"],
            "layout": entry["layout"],
            "comparison": entry["comparison"],
            "sha256": entry["sha256"],
            "byte_count": entry["byte_count"],
        }

    index = {
        "origin": {
            "generator": manifest["generator"],
            "generator_sha256": manifest["generator_sha256"],
            "checkpoint_sha256": manifest["checkpoint_sha256"],
            "upstream_commit": manifest["upstream_commit"],
            "torch_version": manifest["torch_version"],
            "torchvision_version": manifest["torchvision_version"],
            "numpy_version": manifest["numpy_version"],
        },
        "image_preprocessing": manifest["image_preprocessing"],
        "postprocessing": manifest["postprocessing"],
        "preprocessing_boundary": manifest["preprocessing_boundary"],
        "prompt": manifest["prompt"],
        "schema_version": manifest["schema_version"],
        "tensors": copied,
    }
    (OUT / "INDEX.json").write_text(json.dumps(index, indent=2, sort_keys=True) + "\n")
    print(f"edgetam goldens: {len(copied)} tensors verified and staged in {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
